function term(name, category, contexts = [], extra = {}) {
  return {
    term: name,
    category,
    contexts,
    spoken: extra.spoken || [],
    modalities: extra.modalities || [],
    bodyParts: extra.bodyParts || [],
    abbreviation: extra.abbreviation || "",
    ambiguous: Boolean(extra.ambiguous),
  };
}

